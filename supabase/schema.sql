-- Run cleanup every five minutes. Re-running this migration replaces the existing job.
create extension if not exists pg_cron with schema pg_catalog;
do $$
declare existing_job bigint;
begin
  select jobid into existing_job from cron.job where jobname = 'cleanup-expired-board-game-rooms';
  if existing_job is not null then perform cron.unschedule(existing_job); end if;
  perform cron.schedule(
    'cleanup-expired-board-game-rooms',
    '*/5 * * * *',
    'select public.cleanup_expired_game_rooms();'
  );
end $$;
